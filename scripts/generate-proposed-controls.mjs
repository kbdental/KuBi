/**
 * Turn the v3.0 proposals register into something the app can read.
 *
 *   node scripts/generate-proposed-controls.mjs
 *   node scripts/generate-proposed-controls.mjs --check   (exit 1 if stale)
 *
 * ─────────────────────────────────────────────────────────────────────────
 * Why generate rather than hand-write
 * ─────────────────────────────────────────────────────────────────────────
 *
 * docs/requirements/matrix-v3-proposals.tsv is the register the owner reads
 * and edits. If the escalation ladders were also typed into TypeScript by
 * hand, the two would disagree within a month and the screen would name a
 * person the register never named. So the register stays the source and this
 * writes the file. tests/unit/proposed-controls.test.ts re-reads the register
 * and fails if the generated file has drifted.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * What it deliberately does not do
 * ─────────────────────────────────────────────────────────────────────────
 *
 * It does not map job titles onto RoleCode. The register says "Staff/HK" and
 * "HK/Reception"; KuBi has no such roles, and choosing the nearest one would
 * put a name against work nobody agreed to own. The titles are carried as the
 * owner wrote them and rendered as text.
 *
 * It does not fill a DECISION_REQUIRED cell. A proposal with an open field is
 * carried with that field listed in `openDecisions`, which is what stops it
 * being accepted into a v3.0 matrix.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const REGISTER = 'docs/requirements/matrix-v3-proposals.tsv';
const OUT = 'packages/contracts/src/proposed-controls.ts';
const checkOnly = process.argv.includes('--check');

const lines = readFileSync(REGISTER, 'utf8').replace(/\r\n/g, '\n').trimEnd().split('\n');
const head = lines[0].split('\t');
const at = (name) => {
  const i = head.indexOf(name);
  if (i < 0) throw new Error(`${REGISTER} has no column "${name}"`);
  return i;
};

const COL = {
  id: at('Activity ID'),
  parameter: at('Parameter'),
  activity: at('Activity'),
  standard: at('Standard / Expected Result'),
  frequency: at('Frequency'),
  dueRule: at('Due Rule'),
  owner: at('Accountable Owner'),
  l1: at('Escalation L1'),
  l2: at('Escalation L2'),
  l3: at('Escalation L3'),
  kpi: at('KPI'),
  status: at('Status'),
  frozenCheck: at('Frozen Matrix Check'),
};

const rows = lines.slice(1).filter((l) => l.trim() !== '').map((line) => {
  const c = line.split('\t');
  const cell = (i) => (c[i] ?? '').trim();
  const openDecisions = head
    .map((name, i) => (cell(i) === 'DECISION_REQUIRED' ? name : null))
    .filter(Boolean);
  return {
    id: cell(COL.id),
    parameter: cell(COL.parameter),
    activity: cell(COL.activity),
    standard: cell(COL.standard),
    frequency: cell(COL.frequency),
    dueRule: cell(COL.dueRule),
    owner: cell(COL.owner),
    escalation: [cell(COL.l1), cell(COL.l2), cell(COL.l3)].filter((s) => s !== ''),
    kpi: cell(COL.kpi),
    status: cell(COL.status),
    frozenCheck: cell(COL.frozenCheck),
    openDecisions,
  };
});

const q = (s) => JSON.stringify(s);
const body = rows.map((r) => `  {
    id: ${q(r.id)},
    parameter: ${q(r.parameter)},
    activity: ${q(r.activity)},
    standard: ${q(r.standard)},
    frequency: ${r.frequency === 'DECISION_REQUIRED' ? 'null' : q(r.frequency)},
    dueRule: ${r.dueRule === 'DECISION_REQUIRED' ? 'null' : q(r.dueRule)},
    owner: ${q(r.owner)},
    escalation: [${r.escalation.map(q).join(', ')}],
    status: ${q(r.status)},
    frozenCheck: ${q(r.frozenCheck)},
    openDecisions: [${r.openDecisions.map(q).join(', ')}],
  },`).join('\n');

const file = `/**
 * Controls drafted for matrix v3.0, and not yet in force.
 *
 * GENERATED by scripts/generate-proposed-controls.mjs from
 * ${REGISTER}. Do not edit by hand — edit the register.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * Why this file exists at all
 * ─────────────────────────────────────────────────────────────────────────
 *
 * Matrix v2.0 is frozen, so none of these govern anything today. But the
 * owner has decided their escalation — a missed housekeeping round reaches
 * the Clinic Manager — and a decision that lives only in a spreadsheet is a
 * decision the app cannot show anybody. Carrying the proposals here lets a
 * screen say *"would reach the Clinic Manager once HK-001 is accepted"*
 * instead of the blunter and now-misleading *"nobody hears about this"*.
 *
 * The distinction the tests defend: a proposal is never a control. Nothing
 * here is returned by \`ladderFor\`, nothing here counts as \`covers\`, and
 * nothing here makes an ungoverned standard governed. See
 * tests/unit/proposed-controls.test.ts.
 *
 * Job titles are the register's own words, not RoleCode. "Staff/HK" is not a
 * role KuBi has, and guessing which one it meant would name the wrong person.
 */

/** One drafted control, exactly as the register states it. */
export interface ProposedControl {
  /** HK-001, MNT-002, … The id it would carry if accepted. */
  id: string;
  parameter: string;
  activity: string;
  /** What good looks like, in the owner's wording. */
  standard: string;
  /** Null where the register still says DECISION_REQUIRED. */
  frequency: string | null;
  /** Null where the register still says DECISION_REQUIRED. */
  dueRule: string | null;
  /** Accountable owner, as a job title. */
  owner: string;
  /** L1 → L2 → L3, as job titles. Decided, even where the schedule is not. */
  escalation: string[];
  /**
   * PROPOSED, or WITHDRAWN_DUPLICATE where a frozen v2.0 control already does
   * this. Withdrawn rows are kept rather than deleted: the owner has read them,
   * and a proposal that quietly vanishes is indistinguishable from one that was
   * never considered.
   */
  status: string;
  /**
   * The frozen activities this was compared against before being proposed, or
   * NONE_FOUND. Required on every row. Six proposals were withdrawn the day
   * this column was added, because nobody had made that comparison and the
   * frozen matrix already ran them.
   */
  frozenCheck: string;
  /**
   * Register columns still marked DECISION_REQUIRED. Non-empty means this
   * proposal cannot be accepted into a v3.0 matrix yet, whatever else is
   * settled about it.
   */
  openDecisions: string[];
}

export const PROPOSED_CONTROLS: readonly ProposedControl[] = [
${body}
];

/** A drafted control by id, or null. Never falls back to a frozen control. */
export function proposalById(id: string): ProposedControl | null {
  return PROPOSED_CONTROLS.find((p) => p.id === id) ?? null;
}

/** Live proposals. Excludes anything withdrawn as a duplicate of a frozen control. */
export function liveProposals(): ProposedControl[] {
  return PROPOSED_CONTROLS.filter((p) => p.status === 'PROPOSED');
}

/** Live proposals that could be accepted today — nothing left to decide. */
export function readyToAccept(): ProposedControl[] {
  return liveProposals().filter((p) => p.openDecisions.length === 0);
}

/** Withdrawn because the frozen matrix already does this. */
export function withdrawn(): ProposedControl[] {
  return PROPOSED_CONTROLS.filter((p) => p.status === 'WITHDRAWN_DUPLICATE');
}
`;

const existing = (() => {
  try { return readFileSync(OUT, 'utf8'); } catch { return null; }
})();

if (checkOnly) {
  if (existing === file) {
    console.log(`${OUT} is current — ${rows.length} proposals.`);
    process.exit(0);
  }
  console.error(`${OUT} is stale. Run: node scripts/generate-proposed-controls.mjs`);
  process.exit(1);
}

writeFileSync(OUT, file);
const live = rows.filter((r) => r.status === 'PROPOSED');
const open = live.filter((r) => r.openDecisions.length > 0);
console.log(`Wrote ${OUT}: ${rows.length} rows — ${live.length} proposed, `
  + `${rows.length - live.length} withdrawn as duplicates of frozen controls. `
  + `Of the live ones, ${live.length - open.length} ready to accept and `
  + `${open.length} still waiting on a decision.`);
